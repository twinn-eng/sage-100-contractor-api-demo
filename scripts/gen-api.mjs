#!/usr/bin/env node
// Regenerates the API types this app uses from the published Twinn OpenAPI document.
//
//   npm run gen:api                      # fetches https://twinn.engineering/openapi.v3.json
//   npm run gen:api -- ./openapi.v3.yaml # or a local copy (JSON or YAML)
//
// The full contract is large, so this keeps only the routes the app calls (and the schemas they
// reference), writes that subset to api/openapi.json, and generates src/api/schema.d.ts from it.

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { load as parseYaml } from 'js-yaml'
import openapiTS, { astToString } from 'openapi-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = process.argv[2] ?? 'https://twinn.engineering/openapi.v3.json'

const LOOKUPS = [
  'parts',
  'inventory-locations',
  'jobs',
  'job-phases',
  'ledger-accounts',
  'ledger-subaccounts',
  'cost-codes',
  'cost-types',
]
const KEEP = new Map([
  ['/inventory-allocations', ['post']],
  ['/inventory-allocations/query', ['post']],
  ['/inventory-quantities/query', ['post']],
  ['/requests/{id}', ['get']],
  ...LOOKUPS.flatMap((e) => [
    [`/${e}/query`, ['post']],
    [`/${e}/match`, ['post']],
  ]),
])

async function load(src) {
  const text = /^https?:/.test(src) ? await (await fetch(src)).text() : await readFile(src, 'utf8')
  return src.endsWith('.json') ? JSON.parse(text) : parseYaml(text)
}

function prune(doc) {
  const paths = {}
  for (const [path, methods] of KEEP) {
    // The published document lists paths under its /api/v3 server; the source spec may spell them out.
    const item = doc.paths[path] ?? doc.paths[`/api/v3${path}`]
    if (!item) throw new Error(`${path} is not in the contract`)
    const kept = {}
    for (const m of methods) {
      if (!item[m]) throw new Error(`${m.toUpperCase()} ${path} is not in the contract`)
      kept[m] = item[m]
    }
    paths[path] = kept
  }

  // Keep every component reachable from the kept paths.
  const keep = new Set()
  const walk = (v) => {
    if (Array.isArray(v)) return v.forEach(walk)
    if (!v || typeof v !== 'object') return
    for (const [k, x] of Object.entries(v)) {
      if (k === '$ref' && typeof x === 'string' && x.startsWith('#/components/')) {
        if (!keep.has(x)) {
          keep.add(x)
          const [, , kind, name] = x.split('/')
          walk(doc.components[kind][decodeURIComponent(name)])
        }
      } else walk(x)
    }
  }
  walk(paths)
  const components = {}
  for (const ref of [...keep].sort()) {
    const [, , kind, name] = ref.split('/')
    const key = decodeURIComponent(name)
    components[kind] ??= {}
    components[kind][key] = doc.components[kind][key]
  }
  // Vendor extensions are for Twinn's own tooling; only the enum names help a generated client.
  const strip = (v) => {
    if (Array.isArray(v)) return v.forEach(strip)
    if (!v || typeof v !== 'object') return
    for (const k of Object.keys(v)) {
      if (k.startsWith('x-') && k !== 'x-enum-varnames' && k !== 'x-enum-descriptions') delete v[k]
      else strip(v[k])
    }
  }
  strip(paths)
  strip(components)
  return {
    openapi: doc.openapi,
    info: {
      ...doc.info,
      description: 'A subset of the Twinn REST API (version 3): the routes this example calls. The full reference is at https://twinn.engineering/developers.',
    },
    servers: [
      { url: 'https://demo.twinn.engineering/api/v3', description: 'Demo company' },
      { url: 'https://dashboard.twinn.engineering/api/v3', description: 'Your company' },
    ],
    paths,
    components,
  }
}

const subset = prune(await load(source))
await writeFile(join(root, 'api', 'openapi.json'), JSON.stringify(subset, null, 2) + '\n')
// A field with a default is optional on a request, so do not mark it required.
const ast = await openapiTS(subset, { defaultNonNullable: false })
const header = '// Generated by `npm run gen:api` from api/openapi.json. Do not edit by hand.\n\n'
await writeFile(join(root, 'src', 'api', 'schema.d.ts'), header + astToString(ast))
console.log(`api/openapi.json: ${Object.keys(subset.paths).length} paths, ${Object.values(subset.components).reduce((n, c) => n + Object.keys(c).length, 0)} components`)
